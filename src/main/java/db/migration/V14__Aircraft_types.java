package db.migration;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import org.flywaydb.core.api.migration.BaseJavaMigration;
import org.flywaydb.core.api.migration.Context;

/**
 * Replaces the {@code airplane} table with {@code aircraft_type}: kinds of aircraft identified by their ICAO type
 * designator, which flights can reference (V15).
 *
 * <p>{@code airplane} mixed a type (manufacturer, model, speed) with one airline's cabin (seats), had no natural key,
 * an unmapped {@code airline_id} pointing at airlines that do not exist, and a typo in its seed data (V2). Its seven
 * seed rows are replaced by {@link #TYPES}. Any other row was added by an admin and cannot be converted without an
 * ICAO code, so the migration stops rather than lose it: add such rows to {@link #TYPES} (or delete them) and
 * migrate again. Written in Java for that check.
 */
public class V14__Aircraft_types extends BaseJavaMigration {

    private record Type(String icaoCode, String manufacturer, String model, int cruiseSpeedKmh, int typicalSeats) {}

    /** Types used by the seeded airlines (Tarom, British Airways, Air France, Wizz Air); approximate figures. */
    private static final List<Type> TYPES = List.of(
            new Type("A320", "Airbus", "A320", 840, 180),
            new Type("A21N", "Airbus", "A321neo", 840, 230),
            new Type("A333", "Airbus", "A330-300", 870, 300),
            new Type("AT76", "ATR", "72-600", 510, 72),
            new Type("B738", "Boeing", "737-800", 840, 189),
            new Type("B77W", "Boeing", "777-300ER", 905, 396));

    /** The rows V2 inserted, as manufacturer|model|seats|speed|airline_id. */
    private static final Set<String> V2_AIRPLANES = Set.of(
            "Boeing|B373|160|800|1",
            "Boeing|B737|180|700|2",
            "Boeing|B747|200|900|3",
            "Boeing|B777|190|750|4",
            "Airbus|A320|150|800|5",
            "Airbus|A300|160|800|6",
            "Airbus|A340|180|900|7");

    @Override
    public void migrate(Context context) throws Exception {
        Connection connection = context.getConnection();
        requireOnlySeedAirplanes(connection);

        execute(connection, """
                CREATE TABLE aircraft_type (
                    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    icao_code        VARCHAR(4)   NOT NULL,
                    manufacturer     VARCHAR(100) NOT NULL,
                    model            VARCHAR(100) NOT NULL,
                    cruise_speed_kmh INTEGER      NOT NULL,
                    typical_seats    INTEGER,
                    version          BIGINT DEFAULT 0 NOT NULL,
                    CONSTRAINT uk_aircraft_type_icao_code UNIQUE (icao_code),
                    CONSTRAINT ck_aircraft_type_cruise_speed_positive CHECK (cruise_speed_kmh > 0),
                    CONSTRAINT ck_aircraft_type_typical_seats_positive CHECK (typical_seats IS NULL OR typical_seats > 0)
                )
                """);
        try (PreparedStatement insert = connection.prepareStatement("INSERT INTO aircraft_type"
                + " (icao_code, manufacturer, model, cruise_speed_kmh, typical_seats) VALUES (?, ?, ?, ?, ?)")) {
            for (Type type : TYPES) {
                insert.setString(1, type.icaoCode());
                insert.setString(2, type.manufacturer());
                insert.setString(3, type.model());
                insert.setInt(4, type.cruiseSpeedKmh());
                insert.setInt(5, type.typicalSeats());
                insert.addBatch();
            }
            insert.executeBatch();
        }
        execute(connection, "DROP TABLE airplane");
    }

    private static void requireOnlySeedAirplanes(Connection connection) throws SQLException {
        List<String> added = new ArrayList<>();
        try (Statement select = connection.createStatement();
                ResultSet rs = select.executeQuery(
                        "SELECT id, manufacturer, model, number_of_seats, speed, airline_id FROM airplane")) {
            while (rs.next()) {
                String row = rs.getString("manufacturer") + "|" + rs.getString("model") + "|"
                        + rs.getLong("number_of_seats") + "|" + Math.round(rs.getDouble("speed")) + "|"
                        + rs.getLong("airline_id");
                if (!V2_AIRPLANES.contains(row)) {
                    added.add("id " + rs.getLong("id") + " (" + row + ")");
                }
            }
        }
        if (!added.isEmpty()) {
            throw new IllegalStateException("V14: airplanes added after the seed data need an ICAO type code: " + added
                    + "; add them to V14__Aircraft_types.TYPES (or delete them), then migrate again");
        }
    }

    private static void execute(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }
}
